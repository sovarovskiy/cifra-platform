export function getSalesModelSection(sectionId: string): SalesModelSection | undefined {
  return SALES_MODEL_SECTIONS.find((s) => s.id === sectionId);
}

export function getSalesModelPart(
  sectionId: string,
  partId: string
): SalesModelPart | undefined {
  return getSalesModelSection(sectionId)?.parts.find((p) => p.id === partId);
}
