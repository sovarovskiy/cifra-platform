function q(
  id: string,
  topic: string,
  text: string,
  correct: string,
  wrongs: string[],
  explanation: string
): TestQuestion {
  const opts = [
    { id: "a", label: correct, correct: true },
    ...wrongs.slice(0, 3).map((label, i) => ({
      id: String.fromCharCode(98 + i),
      label,
      correct: false,
    })),
  ];
  while (opts.length < 4) {
    opts.push({
      id: String.fromCharCode(97 + opts.length),
      label: `Вариант ${opts.length + 1}`,
      correct: false,
    });
  }
  return { id, topic, text, options: opts, explanation };
}

