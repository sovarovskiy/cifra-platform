function hashSeed(s: string): number {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (Math.imul(31, h) + s.charCodeAt(i)) | 0;
  return h >>> 0;
}

function shuffleOptions(options: TestQuestionOption[], seed: string): TestQuestionOption[] {
  const copy = [...options];
  let state = hashSeed(seed);
  for (let i = copy.length - 1; i > 0; i--) {
    state = (Math.imul(1103515245, state) + 12345) >>> 0;
    const j = state % (i + 1);
    [copy[i], copy[j]] = [copy[j]!, copy[i]!];
  }
  return copy.map((o, idx) => ({
    ...o,
    id: String.fromCharCode(97 + idx),
  }));
}

function q(
  id: string,
  topic: string,
  text: string,
  correct: string,
  wrongs: string[],
  explanation: string
): TestQuestion {
  const opts: TestQuestionOption[] = [
    { id: "a", label: correct, correct: true },
    ...wrongs.slice(0, 3).map((label, i) => ({
      id: String.fromCharCode(98 + i),
      label,
      correct: false,
    })),
  ];
  while (opts.length < 4) {
    opts.push({
      id: String.fromCharCode(97 + opts.length),
      label: `Вариант ${opts.length + 1}`,
      correct: false,
    });
  }
  return {
    id,
    topic,
    text,
    options: shuffleOptions(opts, id),
    explanation,
  };
}

